"""
Evaluation/find_best_checkpoint.py
=================================
Find the best checkpoint from a training run based on success_rate (and
ep_rew_mean as a tiebreaker), then optionally evaluate it.

Usage::

    # Find best checkpoint in a run directory (no evaluation):
    python Evaluation/find_best_checkpoint.py --run Data/Training/.../run_20260520_205732

    # Find and immediately evaluate it (random mode, 50 episodes):
    python Evaluation/find_best_checkpoint.py --run Data/Training/.../run_20260520_205732 \
        --evaluate --episodes 50

    # Find and evaluate with PyBullet GUI (5 episodes):
    python Evaluation/find_best_checkpoint.py --run Data/Training/.../run_20260520_205732 \
        --evaluate --gui --episodes 5

    # Use a specific checkpoint file instead of scanning:
    python Evaluation/find_best_checkpoint.py --run Data/Training/.../run_20260520_205732 \
        --checkpoint Data/Training/.../run_20260520_205732/model/final_model.zip \
        --evaluate --episodes 100

The script reads the ``logs/progress.csv`` generated by stable-baselines3.
It skips rows where ``success_rate`` is NaN and selects the checkpoint with
the highest ``success_rate``; if multiple checkpoints share the same peak
rate, the one with the highest ``ep_rew_mean`` wins.

A model checkpoint file is expected at ``run_dir/model/best_checkpoint_t{timestep}.zip``.
If the file does not exist yet, the script prints the best checkpoint metadata
and exits without evaluating.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path
from typing import Optional

# --------------------------------------------------------------------------- #
# Path setup
# --------------------------------------------------------------------------- #
_SCRIPT_DIR = Path(__file__).resolve().parent
_SRC_DIR = _SCRIPT_DIR.parent / "src"
if str(_SRC_DIR) not in sys.path:
    sys.path.insert(0, str(_SRC_DIR))

# --------------------------------------------------------------------------- #
# Types
# --------------------------------------------------------------------------- #

class CheckpointMetrics:
    """Plain container for checkpoint metrics."""
    __slots__ = (
        "timestep", "success_rate", "ep_rew_mean",
        "collision_rate", "workspace_violation_rate", "max_steps_rate",
        "path_efficiency",
    )

    def __init__(
        self,
        timestep: int,
        success_rate: float,
        ep_rew_mean: float,
        collision_rate: float,
        workspace_violation_rate: float,
        max_steps_rate: float,
        path_efficiency: Optional[float],
    ):
        self.timestep = timestep
        self.success_rate = success_rate
        self.ep_rew_mean = ep_rew_mean
        self.collision_rate = collision_rate
        self.workspace_violation_rate = workspace_violation_rate
        self.max_steps_rate = max_steps_rate
        self.path_efficiency = path_efficiency

    def __repr__(self) -> str:
        pe = (
            f", path_efficiency={self.path_efficiency:.2f}%"
            if self.path_efficiency is not None
            else ""
        )
        return (
            f"CheckpointMetrics(timestep={self.timestep}, "
            f"success_rate={self.success_rate:.4f}, "
            f"ep_rew_mean={self.ep_rew_mean:.4f}, "
            f"collision_rate={self.collision_rate:.4f}, "
            f"workspace_violation_rate={self.workspace_violation_rate:.4f}, "
            f"max_steps_rate={self.max_steps_rate:.4f}{pe})"
        )


# --------------------------------------------------------------------------- #
# CSV parsing
# --------------------------------------------------------------------------- #

def _parse_progress_csv(csv_path: Path) -> list[CheckpointMetrics]:
    """
    Parse a stable-baselines3 progress.csv and return a list of CheckpointMetrics.

    Rows where ``success_rate`` is NaN / empty are skipped.  Rows with NaN in
    secondary columns (ep_rew_mean, etc.) are included but those fields are
    set to NaN in the returned object so callers can decide how to handle them.
    """
    checkpoints: list[CheckpointMetrics] = []

    with open(csv_path, newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            sr_raw = row.get("rollout/success_rate", "").strip()
            if not sr_raw:
                continue
            try:
                success_rate = float(sr_raw)
            except ValueError:
                continue

            def _f(key: str) -> float:
                v = row.get(key, "").strip()
                return float(v) if v else float("nan")

            ts_raw = row.get("time/total_timesteps", "").strip()
            timestep = int(float(ts_raw)) if ts_raw else 0

            path_eff_raw = row.get("rollout/success_path_efficiency_percent_mean", "").strip()
            path_eff: Optional[float] = float(path_eff_raw) if path_eff_raw else None

            checkpoints.append(CheckpointMetrics(
                timestep=timestep,
                success_rate=success_rate,
                ep_rew_mean=_f("rollout/ep_rew_mean"),
                collision_rate=_f("rollout/collision_rate"),
                workspace_violation_rate=_f("rollout/workspace_violation_rate"),
                max_steps_rate=_f("rollout/max_steps_rate"),
                path_efficiency=path_eff,
            ))

    return checkpoints


# --------------------------------------------------------------------------- #
# Checkpoint selection
# --------------------------------------------------------------------------- #

def find_best_checkpoint(checkpoints: list[CheckpointMetrics]) -> CheckpointMetrics:
    """
    Return the checkpoint with the highest ``success_rate``.
    Tiebreaker: highest ``ep_rew_mean``.
    """
    if not checkpoints:
        raise ValueError("No checkpoints provided")

    best = max(
        checkpoints,
        key=lambda c: (c.success_rate, c.ep_rew_mean),
    )
    return best


# --------------------------------------------------------------------------- #
# Checkpoint model file resolution
# --------------------------------------------------------------------------- #

def resolve_checkpoint_model(
    run_dir: Path,
    best: CheckpointMetrics,
) -> Optional[Path]:
    """
    Look for a saved checkpoint that matches the given best timestep.

    Search order:
      1. run_dir/model/best_checkpoint_t{timestep}.zip  (specific peak checkpoint)
      2. run_dir/model/best_model.zip                 (rolling best from callback)
      3. run_dir/model/final_model.zip                 (final model)
      4. run_dir/final_model.zip

    Returns the resolved Path or None if no model file is found.
    """
    candidates = [
        run_dir / "model" / f"best_checkpoint_t{best.timestep}.zip",
        run_dir / "model" / "best_model.zip",
        run_dir / "model" / "final_model.zip",
        run_dir / "final_model.zip",
    ]
    for p in candidates:
        if p.exists():
            return p.resolve()
    return None


# --------------------------------------------------------------------------- #
# Pretty printing
# --------------------------------------------------------------------------- #

def print_checkpoint_table(
    checkpoints: list[CheckpointMetrics],
    best: CheckpointMetrics,
    top_n: int = 10,
) -> None:
    """Print a summary table of the top-N checkpoints."""
    # Sort by success_rate desc, ep_rew_mean desc
    sorted_cps = sorted(
        checkpoints,
        key=lambda c: (c.success_rate, c.ep_rew_mean),
        reverse=True,
    )[:top_n]

    header = (
        f"{'Rank':>4} | {'Timestep':>10} | {'Success Rate':>13} | "
        f"{'ep_rew_mean':>13} | {'Collision':>10} | "
        f"{'WS Viol.':>10} | {'Max Steps':>10} | {'Path Eff.':>10}"
    )
    sep = "-" * len(header)

    print("\n" + "=" * len(header))
    print("  Top checkpoints by success_rate (tiebreaker: ep_rew_mean)")
    print("=" * len(header))
    print(header)
    print(sep)

    for rank, cp in enumerate(sorted_cps, 1):
        pe_str = f"{cp.path_efficiency:>9.2f}%" if cp.path_efficiency is not None else "      N/A"
        marker = " <-- BEST" if cp is best else ""
        print(
            f"{rank:>4} | {cp.timestep:>10,} | {cp.success_rate:>12.4f} | "
            f"{cp.ep_rew_mean:>12.4f} | {cp.collision_rate:>9.4f} | "
            f"{cp.workspace_violation_rate:>9.4f} | {cp.max_steps_rate:>9.4f} | "
            f"{pe_str}{marker}"
        )

    print(sep)
    print(f"  Total checkpoints evaluated: {len(checkpoints)}")


def print_best_summary(best: CheckpointMetrics, model_path: Optional[Path]) -> None:
    """Print the selected best checkpoint summary."""
    print("\n" + "=" * 60)
    print("  BEST CHECKPOINT")
    print("=" * 60)
    print(f"  Timestep                : {best.timestep:,}")
    print(f"  Success Rate            : {best.success_rate:.4f}  ({best.success_rate*100:.2f}%)")
    print(f"  Episode Reward Mean      : {best.ep_rew_mean:.4f}")
    print(f"  Collision Rate           : {best.collision_rate:.4f}  ({best.collision_rate*100:.2f}%)")
    print(f"  Workspace Violation Rate : {best.workspace_violation_rate:.4f}  ({best.workspace_violation_rate*100:.2f}%)")
    print(f"  Max Steps Rate          : {best.max_steps_rate:.4f}  ({best.max_steps_rate*100:.2f}%)")
    if best.path_efficiency is not None:
        print(f"  Path Efficiency (succ.)  : {best.path_efficiency:.4f}  ({best.path_efficiency:.2f}%)")
    else:
        print(f"  Path Efficiency (succ.)  : N/A")
    if model_path is not None:
        print(f"  Model File              : {model_path}")
    else:
        print(f"  Model File              : NOT FOUND (run may still be training)")
    print("=" * 60)


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Find the best checkpoint from a training run and optionally evaluate it.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--run",
        type=str,
        required=True,
        help="Path to the training run directory (e.g. run_20260520_205732)",
    )
    parser.add_argument(
        "--checkpoint",
        type=str,
        default=None,
        help=(
            "Path to a specific checkpoint .zip to evaluate. "
            "If omitted, the best checkpoint is auto-detected from progress.csv."
        ),
    )
    parser.add_argument(
        "--evaluate",
        action="store_true",
        help="If set, automatically evaluate the best checkpoint after selection.",
    )
    parser.add_argument(
        "--episodes",
        type=int,
        default=50,
        help="Number of evaluation episodes (default: 50).",
    )
    parser.add_argument(
        "--gui",
        action="store_true",
        help="Enable PyBullet GUI during evaluation.",
    )
    parser.add_argument(
        "--deterministic",
        action="store_true",
        default=True,
        help="Use deterministic policy during evaluation (default: True).",
    )
    parser.add_argument(
        "--top-n",
        type=int,
        default=10,
        help="Number of top checkpoints to show in summary table (default: 10).",
    )
    args = parser.parse_args()

    # ------------------------------------------------------------------ #
    # Resolve run directory
    # ------------------------------------------------------------------ #
    run_dir = Path(args.run).resolve()
    if not run_dir.exists():
        print(f"[ERROR] Run directory not found: {run_dir}")
        return 1

    # ------------------------------------------------------------------ #
    # Locate progress.csv
    # ------------------------------------------------------------------ #
    progress_csv = run_dir / "logs" / "progress.csv"
    if not progress_csv.exists():
        # Try alternative location
        alt = run_dir / "progress.csv"
        if alt.exists():
            progress_csv = alt
        else:
            print(f"[ERROR] progress.csv not found in {run_dir / 'logs'} or {run_dir}")
            return 1

    print(f"[INFO] Reading progress.csv: {progress_csv}")

    # ------------------------------------------------------------------ #
    # Parse and find best
    # ------------------------------------------------------------------ #
    checkpoints = _parse_progress_csv(progress_csv)
    if not checkpoints:
        print("[ERROR] No valid checkpoints found in progress.csv (no rows with success_rate)")
        return 1

    best = find_best_checkpoint(checkpoints)

    # ------------------------------------------------------------------ #
    # Resolve model file
    # ------------------------------------------------------------------ #
    model_path: Optional[Path] = None
    if args.checkpoint:
        model_path = Path(args.checkpoint).resolve()
        if not model_path.exists():
            print(f"[WARNING] Specified checkpoint not found: {model_path}")
            model_path = None
    else:
        model_path = resolve_checkpoint_model(run_dir, best)

    # ------------------------------------------------------------------ #
    # Print results
    # ------------------------------------------------------------------ #
    print_best_summary(best, model_path)
    print_checkpoint_table(checkpoints, best, top_n=args.top_n)

    # ------------------------------------------------------------------ #
    # Evaluate if requested
    # ------------------------------------------------------------------ #
    if args.evaluate:
        if model_path is None:
            print(
                "\n[WARNING] No model file found for best checkpoint. "
                "The run may still be in progress. Skipping evaluation."
            )
            return 0

        predict_script = _SCRIPT_DIR / "predict_model.py"
        if not predict_script.exists():
            print(f"[ERROR] predict_model.py not found at {predict_script}")
            return 1

        cmd = [
            sys.executable,
            str(predict_script),
            "--run", str(run_dir),
            "--mode", "random",
            "--episodes", str(args.episodes),
            "--deterministic", "true" if args.deterministic else "false",
            "--gui", "true" if args.gui else "false",
            "--show", "true",
        ]

        print(f"\n[INFO] Starting evaluation with {args.episodes} episodes...")
        print(f"[INFO] Command: {' '.join(cmd)}")
        import subprocess
        result = subprocess.run(cmd, cwd=str(_SCRIPT_DIR.parent))
        if result.returncode != 0:
            print(f"[ERROR] Evaluation script returned exit code {result.returncode}")
            return result.returncode

    print("\n[INFO] Done.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
